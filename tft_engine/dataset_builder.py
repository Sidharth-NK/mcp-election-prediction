"""
TFT Dataset Builder
===================
Iterates across multiple constituencies to build the historical sequence 
DataFrame required for the PyTorch Forecasting Temporal Fusion Transformer.

Because PyTorch Forecasting requires a specific tabular format 
(Pandas DataFrame), this script converts the nested JSON payload 
from fusion_layer.py into a flat, well-structured table.
"""

import os
import json
import asyncio
import pandas as pd
from typing import List, Dict

# Add parent directory to path so we can import agents
import sys
sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from agents.fusion_layer import build_tft_feature_vector

def load_all_targets_from_wiki() -> List[Dict]:
    """
    Dynamically loads all constituencies by reading the output generated by the WikiAgent.
    This guarantees perfectly synced (state, district, constituency) mappings 
    for all data processing.
    """
    # Assuming wiki agent exported its flat candidates representation
    wiki_path = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "wiki_agent_candidates.json"))
    
    if not os.path.exists(wiki_path):
        print(f"Warning: {wiki_path} not found. Returning empty list.")
        return []
        
    with open(wiki_path, "r", encoding="utf-8") as f:
        candidates = json.load(f)
        
    targets_map = {}
    for c in candidates:
        # Deduplicate multiple candidates down to unique constituencies
        key = f"{c['state']}::{c['constituency']}"
        if key not in targets_map:
            targets_map[key] = {
                "state": c["state"],
                "district": c["district"],
                "constituency": c["constituency"]
            }
            
    return list(targets_map.values())

TARGETS = load_all_targets_from_wiki()


def flatten_fusion_payload(payload: Dict) -> Dict:
    """Flattens the nested dictionary into a single-level dict for Pandas."""
    flat_record = {
        "timestamp": payload["timestamp"],
        "time_idx": payload["time_idx"],
        
        # Static Categoricals
        "state": payload["static_categoricals"]["state"],
        "district": payload["static_categoricals"]["district"],
        "constituency": payload["static_categoricals"]["constituency"],
        "past_winner_party": payload["static_categoricals"]["past_winner_party"],
        
        # Static Reals
        "rural_percentage": payload["static_reals"]["rural_percentage"],
        "urban_percentage": payload["static_reals"]["urban_percentage"],
        "literacy_rate": payload["static_reals"]["literacy_rate"],
        "sc_st_percentage": payload["static_reals"]["sc_st_percentage"],
        "past_winning_margin": payload["static_reals"]["past_winning_margin"],
        "past_voter_turnout": payload["static_reals"]["past_voter_turnout"],
        
        # Time-Varying Categoricals
        "risk_level": payload["time_varying_unknown_categoricals"].get("risk_level", "LOW"),
        
        # Time-Varying Reals
        "sentiment_score": payload["time_varying_unknown_reals"].get("sentiment_score", 0.0),
        "event_severity": payload["time_varying_unknown_reals"].get("event_severity", 0.0),
    }
    
    # Dynamically extract polling numbers
    for k, v in payload["time_varying_unknown_reals"].items():
        if k.startswith("poll_"):
            flat_record[k] = v
            
    return flat_record

async def build_dataset(targets: List[Dict], time_idx: int = 0) -> pd.DataFrame:
    """
    Builds a single 'time step' matrix for all targets.
    In a real training loop, you would run this daily/weekly over several months 
    and increment time_idx.
    """
    print(f"Building Dataset for time_idx = {time_idx}")
    
    records = []
    for t in targets:
        try:
            payload = await build_tft_feature_vector(
                state=t["state"],
                district=t["district"],
                constituency=t["constituency"],
                time_idx=time_idx
            )
            flat = flatten_fusion_payload(payload)
            records.append(flat)
        except Exception as e:
            print(f"  [!] Failed processing {t['constituency']}: {e}")
            
    df = pd.DataFrame(records)
    
    # Fill NaN polling values with 0.0 for safety (PyTorch Forecasting hates NaNs)
    df = df.fillna(0.0)
    
    # Ensure types are correct for PyTorch
    df['time_idx'] = df['time_idx'].astype(int)
    for col in ['state', 'district', 'constituency', 'past_winner_party', 'risk_level']:
        df[col] = df[col].astype(str)
        
    return df

if __name__ == "__main__":
    async def main():
        df = await build_dataset(TARGETS, time_idx=0)
        
        print("\n=== FINAL TFT DATAFRAME HEAD ===")
        print(df.head())
        
        # Ensure output directory exists (relative to script)
        script_dir = os.path.dirname(__file__)
        out_dir = os.path.join(script_dir, "data")
        os.makedirs(out_dir, exist_ok=True)
        
        out_path = os.path.join(out_dir, "tft_dataset_step0.csv")
        df.to_csv(out_path, index=False)
        print(f"\nSaved dataset to {out_path}")

    asyncio.run(main())
