"""
TFT Model Training Engine
=========================
Trains PyTorch Forecasting's Temporal Fusion Transformer (TFT) on the 
data generated by `dataset_builder.py`.

The model takes the fused matrix and predicts a future signal
based on:
- Static sociodemographics (literacy, urban %, past margins)
- Dynamic Gemini sentiment & risk levels
"""

import os
import sys

try:
    import pandas as pd
    import torch
    import pytorch_lightning as pl
    from pytorch_forecasting import TimeSeriesDataSet, TemporalFusionTransformer
    from pytorch_forecasting.data import GroupNormalizer
    from pytorch_forecasting.metrics import QuantileLoss
except ImportError:
    print("PyTorch Forecasting dependencies not found.")
    print("Please run: pip install torch pytorch-lightning pytorch-forecasting pandas")
    print("Exiting...")
    sys.exit(1)


def load_dataset_and_prepare(csv_path: str) -> TimeSeriesDataSet:
    """Loads combined TFT dataset and maps columns to their respective temporal types."""
    # In a fully running system, you would merge multiple daily/weekly generated CSVs into one massive dataframe
    df = pd.read_csv(csv_path)

    # Ensure categoricals are strictly string types
    categoricals = ["state", "district", "constituency", "past_winner_party", "risk_level"]
    for col in categoricals:
        df[col] = df[col].astype(str)

    # Since we are predicting a future numeric margin / outcome, we use "target_margin"
    # For now, we simulate a target label to establish the architecture compilation 
    if 'target_margin' not in df.columns:
        df['target_margin'] = df['sentiment_score'] * 10 + df['past_winning_margin']

    # time_idx must be a continuous integer sequence
    df['time_idx'] = df['time_idx'].astype(int)
    
    # We fake the max sequence here for Day 0 testing.
    # In reality, min_encoder_length will be set to looking back ~5-10 days
    training = TimeSeriesDataSet(
        df,
        time_idx="time_idx",
        target="target_margin",
        group_ids=["state", "constituency"],
        min_encoder_length=1, 
        max_encoder_length=1,   # How far back the Attention heads look
        min_prediction_length=1,
        max_prediction_length=1, # How many days into the future we predict
        
        # Mapping our specific fused pipeline features to the TFT Architecture:
        static_categoricals=["state", "district", "past_winner_party"],
        static_reals=["rural_percentage", "urban_percentage", "literacy_rate", "sc_st_percentage", "past_winning_margin", "past_voter_turnout"],
        time_varying_known_categoricals=[],    # E.g. Voting phase schedule, Day of Week
        time_varying_known_reals=["time_idx"], # Time is always known tracking forward
        time_varying_unknown_categoricals=["risk_level"],                 # Dynamic Node: Political risk tag 
        time_varying_unknown_reals=["sentiment_score", "event_severity"], # Dynamic Node: News Sentiment 
        
        target_normalizer=GroupNormalizer(
            groups=["state", "constituency"], transformation="softplus"
        ),
        add_relative_time_idx=True,
        add_target_scales=True,
        add_encoder_length=True,
    )

    return training


def build_and_train_tft(training_dataset: TimeSeriesDataSet):
    """Instantiates and trains the Temporal Fusion Transformer network."""
    
    # Create datalowders (batch processing via PyTorch)
    train_dataloader = training_dataset.to_dataloader(train=True, batch_size=32, num_workers=0)
    
    # PyTorch Lightning execution setup
    trainer = pl.Trainer(
        max_epochs=5,
        accelerator="auto",
        enable_model_summary=True,
        gradient_clip_val=0.1
    )

    # Map dataset architecture straight into the model
    tft = TemporalFusionTransformer.from_dataset(
        training_dataset,
        learning_rate=0.03,
        hidden_size=16,          # Internal layer shapes
        attention_head_size=4,   # TFT's signature Multi-Head Attention blocks
        dropout=0.1,             
        hidden_continuous_size=8,
        output_size=7,           # Outputs 7 Quantiles (Probabilistic intervals like P10, P50, P90)
        loss=QuantileLoss(),     # Quantile loss gives us the exact win margins + confidence scores
        log_interval=1,
        reduce_on_plateau_patience=4
    )

    print(f"Number of parameters in network: {tft.size()/1e3:.1f}k")
    
    print("\n--- Starting Training Loop ---")
    trainer.fit(
        tft,
        train_dataloaders=train_dataloader
    )
    print("--- Training Complete ---")

if __name__ == "__main__":
    script_dir = os.path.dirname(__file__)
    data_path = os.path.join(script_dir, "data", "tft_dataset_step0.csv")
    
    if not os.path.exists(data_path):
        print(f"Dataset not found at {data_path}.")
        print("Please run dataset_builder.py first to generate the historical context.")
    else:
        print("Loading dataset and initializing TFT model...")
        dataset = load_dataset_and_prepare(data_path)
        build_and_train_tft(dataset)
